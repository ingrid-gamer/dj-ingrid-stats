-- 9. ÚLTIMAS 20 REPRODUCCIONES
CREATE OR REPLACE VIEW public.view_recent_plays
WITH (security_invoker = false)
AS
SELECT
    id,
    track_name,
    artist_name,
    album_name,
    album_cover,
    spotify_track_uri,
    played_at,
    ms_played
FROM public.spotify_history_extended
WHERE ms_played > 0
  AND BTRIM(track_name) <> ''
  AND BTRIM(artist_name) <> ''
ORDER BY played_at DESC, id DESC
LIMIT 20;

